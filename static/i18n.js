(function () {
  let lang = "ar";
  try { lang = localStorage.getItem("lang") || "ar"; } catch (e) { /* storage unavailable */ }
  if (!window.I18N[lang]) lang = "ar";

  window.t = function (key, vars) {
    let s = (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.en[key] || key;
    if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    return s;
  };
  window.getLang = () => lang;
  window.setLang = function (next) {
    lang = window.I18N[next] ? next : "ar";
    try { localStorage.setItem("lang", lang); } catch (e) { /* ignore */ }
    window.applyI18n();
  };
  window.applyI18n = function () {
    const d = window.I18N[lang];
    document.documentElement.lang = lang;
    document.documentElement.dir = d.dir;
    document.title = d.title;
    document.querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  };
  window.applyI18n();
})();
